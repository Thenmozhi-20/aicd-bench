"""Zero-shot / CoT LLM classification (Gemini-2.5-Flash via API, or any HF causal LM e.g. Gemma3-27B)."""
import os
import re
import numpy as np
from tqdm import tqdm

ZS = {
 1: "Reply with exactly one word Human or AI. Given this code, identify its origin\n{code}",
 2: "Reply with exactly one word from this list: human, deepseek-ai, Qwen, 01-ai, bigcode, Gemma, Phi, meta-llama, "
    "ibm-granite, mistralai, OpenAI, Gemini. Given this code, identify its origin\n{code}",
 3: "Reply with exactly one word Human, AI, Hybrid or Adversarial. Given this code, was it written by Human, AI, in "
    "Hybrid collaboration or by an Adversarial model which tried to fool the detector mimicing human?\n{code}",
}

_SIGNALS = """- Naming: verbosity/descriptiveness, camelCase/snake_case consistency, oddly generic names.
- Comments/docstrings: density, uniform template-like phrasing, section headers, per-function summaries.
- Type hints & annotations: pervasive, perfectly consistent typing vs. ad-hoc/mixed usage.
- Structure/style: formatter fingerprints (Black/Prettier), tidy imports, exhaustive edge-cases, spotless spacing; versus idiosyncratic style, inconsistencies, TODO/WIP markers.
- Boilerplate/templates: license blocks, README headers, instructional comments, scaffolded regions, foo/bar placeholders.
- API/library usage: unused imports, verbose defensive code, redundant checks, generic logging.
- Testing/examples: synthetic data, contrived examples, pedantic error messages.
- AI artifacts: phrases like "This function ...", tutorial-like narration, code mirroring common LLM examples.
- Human artifacts: partial implementations, inline hacks, commented-out experiments, domain shortcuts, mismatched styles, quick fixes."""

_PROFILES = """- OpenAI: PEP8-clean Python, f-strings, moderate type hints, Google/NumPy docstrings, careful edge-case checks.
- Gemini: verbose instructional comments, TF/JAX-friendly snippets, longer docstrings with bullets.
- meta-llama: PyTorch-first demos, concise comments, torchvision/transformers idioms, manual seeds.
- mistralai: compact Python, minimal ceremony, itertools/collections, terse errors/tests.
- Qwen: occasional bilingual tokens/comments, pandas/NumPy-heavy utilities, explicit dtype handling.
- deepseek-ai: performance-leaning tweaks, vectorization/numba hints, assert-style checks.
- 01-ai: straightforward baseline patterns, minimal comments, direct loops.
- bigcode: repository/tooling scaffolds, license headers, codegen-ready templates, typed stubs.
- Gemma: JAX/Flax hints or TF ops, functional utilities, explicit shapes in comments.
- Phi: didactic step-by-step snippets, simple class wrappers, explicit prints/logs.
- ibm-granite: enterprise-style structure, logger config blocks, clear exceptions/messages.
- human: mixed styles/inconsistencies, partial impls/TODOs, pragmatic hacks, commented-out experiments."""

COT = {
 1: "You are a code-origin classifier. Infer whether a given code snippet was written by a Human or an AI assistant.\n"
    "Reason silently and do NOT reveal your reasoning. Output exactly one word: Human or AI.\n"
    "Consider (but do not list) signals such as:\n" + _SIGNALS +
    "\nIf uncertain, choose the more likely origin using the balance of signals. Respond with a single word only.\nCode:\n```{code}```",
 2: "You are a code-origin classifier. Infer which single author produced the code: human, deepseek-ai, Qwen, 01-ai, "
    "bigcode, Gemma, Phi, meta-llama, ibm-granite, mistralai, OpenAI, Gemini.\n"
    "Think silently to compare candidate profiles; do not reveal reasoning. Output exactly one word: one of the labels above.\n"
    "Use discriminative code-level signals (language & libs, structure, textual style, artifacts).\n"
    "CANDIDATE PROFILES (heuristics; match by best fit):\n" + _PROFILES +
    "\nIf uncertain, choose the single most plausible author by strongest profile match.\nCode:\n```{code}```",
 3: "You are a code-origin classifier. Infer whether a given code snippet was written by a Human, an AI assistant, "
    "Hybridly generated, or generated by an Adversarial model trained to mimic humans and fool detectors.\n"
    "Reason silently and do NOT reveal your reasoning. Output exactly one word: Human, AI, Hybrid, or Adversarial.\n"
    "Consider (but do not list) signals such as:\n" + _SIGNALS +
    "\nIf uncertain, choose the more likely origin using the balance of signals. Again: respond with a single word only.\n"
    "Classify the origin of this code as Human, AI, Hybrid, or Adversarial.\nCode:\n```{code}```",
}


def build_prompt(task, mode, code):
    return (COT if mode == "cot" else ZS)[task].replace("{code}", code)


def _norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def parse(answer, class_names, fallback):
    a = _norm(answer)
    names = [_norm(n) for n in class_names]
    for i, n in enumerate(names):
        if a == n:
            return i
    for i, n in sorted(enumerate(names), key=lambda x: -len(x[1])):  # longest containment first
        if n and n in a:
            return i
    return fallback


def make_backend(kind, model):
    if kind == "gemini":
        from google import genai
        client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])
        return lambda p: client.models.generate_content(model=model, contents=p).text or ""
    import torch
    from transformers import pipeline
    pipe = pipeline("text-generation", model=model, torch_dtype=torch.bfloat16, device_map="auto")
    def gen(p):
        o = pipe([{"role": "user", "content": p}], max_new_tokens=8, do_sample=False)
        return o[0]["generated_text"][-1]["content"]
    return gen


def classify(codes, task, mode, class_names, fallback, backend, max_chars=6000):
    preds = []
    for c in tqdm(codes):
        try:
            ans = backend(build_prompt(task, mode, c[:max_chars]))
        except Exception as e:
            print("LLM error:", e); ans = ""
        preds.append(parse(ans, class_names, fallback))
    return np.array(preds)
